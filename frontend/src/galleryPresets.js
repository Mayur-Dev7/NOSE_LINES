export function normalizeVector(vec) {
  if (!vec || !vec.length) return [];
  let sumSq = 0;
  for (let i = 0; i < vec.length; i++) sumSq += vec[i] * vec[i];
  const norm = Math.sqrt(sumSq) || 1e-8;
  return vec.map(v => v / norm);
}

export function computeBiometricDistance(vecA, vecB) {
  if (!vecA || !vecB || vecA.length !== vecB.length || vecA.length === 0) {
    return { similarityPct: 0, l2Distance: 2.0 };
  }
  const nA = normalizeVector(vecA);
  const nB = normalizeVector(vecB);
  let dot = 0;
  let l2Sq = 0;
  for (let i = 0; i < nA.length; i++) {
    dot += nA[i] * nB[i];
    const diff = nA[i] - nB[i];
    l2Sq += diff * diff;
  }
  const simPct = Math.max(0, Math.min(100, Number((dot * 100).toFixed(2))));
  const l2Dist = Number(Math.sqrt(Math.max(0, l2Sq)).toFixed(4));
  return { similarityPct: simPct, l2Distance: l2Dist };
}

export function runClientSide1toNMatch(queryEmbedding, gallery, threshold = 88.0) {
  if (!queryEmbedding || !queryEmbedding.length) {
    return { success: false, error: 'Query embedding is empty' };
  }
  const candidates = gallery && gallery.length > 0 ? gallery : DEFAULT_GALLERY_CANDIDATES;
  const leaderboard = candidates.map(cand => {
    const { similarityPct, l2Distance } = computeBiometricDistance(queryEmbedding, cand.embedding);
    let verdict = 'DISTINCT';
    let verdictColor = 'rose';
    if (similarityPct >= 88.0) {
      verdict = 'MATCH';
      verdictColor = 'emerald';
    } else if (similarityPct >= 78.0) {
      verdict = 'LIKELY MATCH';
      verdictColor = 'teal';
    } else if (similarityPct >= 65.0) {
      verdict = 'INCONCLUSIVE';
      verdictColor = 'amber';
    }
    return {
      id: cand.id,
      name: cand.name,
      tag: cand.tag || 'N/A',
      breed: cand.breed || 'Unknown',
      registered_date: cand.registered_date || '',
      similarity_pct: similarityPct,
      l2_distance: l2Distance,
      is_match: similarityPct >= threshold,
      verdict,
      verdict_color: verdictColor
    };
  });

  leaderboard.sort((a, b) => b.similarity_pct - a.similarity_pct);
  leaderboard.forEach((item, index) => {
    item.rank = index + 1;
  });

  const topMatch = leaderboard[0] || null;
  const secondMatch = leaderboard[1] || null;
  const marginAhead = topMatch && secondMatch 
    ? Number((topMatch.similarity_pct - secondMatch.similarity_pct).toFixed(1))
    : (topMatch ? Number(topMatch.similarity_pct.toFixed(1)) : 0);

  const isMatch = topMatch ? topMatch.similarity_pct >= threshold : false;
  const verdictText = isMatch 
    ? `MATCH FOUND: ${topMatch.name}`
    : 'NO MATCH (All Distinct Animals)';

  return {
    success: true,
    top_match: topMatch ? { ...topMatch, margin_ahead_pct: marginAhead } : null,
    verdict: verdictText,
    verdict_is_match: isMatch,
    verdict_color: isMatch ? 'emerald' : 'rose',
    margin_ahead_pct: marginAhead,
    threshold,
    leaderboard,
    total_gallery_candidates: leaderboard.length
  };
}
